    fun pack(lang: Lang): Pack = packs[lang] ?: (if (lang == Lang.TRP) packs[Lang.BN] else null) ?: packs.getValue(Lang.EN)

    fun headline(level: Level, lang: Lang): String =
        if (level == Level.SCAM) pack(lang).scam else pack(lang).suspicious

    fun advice(category: Category, lang: Lang): String = pack(lang).let { p ->
        when (category) {
            Category.DIGITAL_ARREST -> p.arrest
            Category.UPI_FRAUD -> p.upi
            Category.OTP_THEFT -> p.otp
            Category.KYC_BLOCK -> p.kyc
            Category.LOTTERY -> p.lottery
            Category.JOB_TASK -> p.job
            Category.LOAN -> p.loan
            Category.SCAM_CALL -> p.callWarn
            Category.PHISHING_LINK, Category.GENERIC -> p.link
        }
    }

    fun helpline(lang: Lang) = pack(lang).helpline
    fun understood(lang: Lang) = pack(lang).understood
    fun call1930(lang: Lang) = pack(lang).call1930
    fun reportChakshu(lang: Lang) = pack(lang).chakshu

    fun spoken(v: Verdict, lang: Lang): String =
        headline(v.level, lang) + " " + advice(v.category, lang) +
            if (v.level == Level.SCAM) " " + helpline(lang) else ""

    fun allLangsHaveText(): Boolean = Lang.values().all { it in packs || it == Lang.TRP }

    fun categoryName(c: Category): String = when (c) {
        Category.DIGITAL_ARREST -> "digital arrest"
        Category.UPI_FRAUD -> "UPI fraud"
        Category.OTP_THEFT -> "OTP theft"
        Category.KYC_BLOCK -> "fake KYC / account block"
        Category.LOTTERY -> "lottery / prize"
        Category.JOB_TASK -> "job / task"
        Category.LOAN -> "loan app"
        Category.PHISHING_LINK -> "phishing link"
        Category.SCAM_CALL -> "scam call"
        Category.GENERIC -> "suspicious"
    }
